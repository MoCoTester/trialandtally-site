def header(lang, current, other_path):
    c = CHROME[lang]
    prefix = "/es" if lang == "es" else ""
    home = f"{prefix}/"

    def link(href, label, key, cls=""):
        cur = ' aria-current="page"' if key == current else ""
        cls_attr = f' class="{cls}"' if cls else ""
        return f'<li{cls_attr}><a href="{href}"{cur}>{label}</a></li>'

    if current == "home":
        items = [link("#how", c["how"], "", "nav-anchor"), link("#demo", c["try"], "", "nav-anchor"),
                 link("#pricing", c["pricing"], "", "nav-anchor"), link(f"{prefix}/support/", c["support"], "support")]
    else:
        items = [link(home, c["home"], "home"), link(f"{prefix}/support/", c["support"], "support"),
                 link(f"{prefix}/privacy/", c["privacy"], "privacy"), link(f"{prefix}/terms/", c["terms"], "terms")]
    other = "en" if lang == "es" else "es"
    nav_items = "\n          ".join(items)
    return f"""<body class="page-{current}">
  <a class="skip" href="#main">{c["skip"]}</a>
  <header class="site-header">
    <div class="wrap header-row">
      <a class="brand" href="{home}"><img src="/apple-touch-icon.png" alt="" width="32" height="32"><span>Trial&amp;Tally</span></a>
      <nav class="site-nav" aria-label="{c["nav_label"]}">
        <ul>
          {nav_items}
        </ul>
      </nav>
      <nav class="lang" aria-label="{c["lang_label"]}">
        <a href="{other_path}" hreflang="{other}" lang="{other}" title="{c["other_lang_title"]}">{c["other_lang_name"]}</a>
      </nav>
    </div>
  </header>"""


