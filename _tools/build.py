def read(*parts):
    with open(os.path.join(*parts), encoding="utf-8") as fh:
        return fh.read()


def load_config():
    return json.loads(read(SRC, "config.json"))


def asset_version(rel):
    """Short content hash for cache busting (?v=...)."""
    with open(os.path.join(ROOT, rel), "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()[:10]


def fill(template, ctx, where):
    def sub(m):
        key = m.group(1)
        if key not in ctx:
            raise KeyError(f"{where}: no value for {{{{{key}}}}}")
        return str(ctx[key])
    return re.sub(r"\{\{([a-zA-Z0-9_\-]+)\}\}", sub, template)


def attr(text):
    """Text for an HTML attribute. Strings in _src are already HTML (&amp;), so only quote marks
    and tags need care."""
    return re.sub(r"<[^>]+>", "", text).replace('"', "&quot;")


# ---------------------------------------------------------------- snippets

def picture(lang, shot, alt, eager=False, cls=""):
    base = f"/assets/img/shots/{lang}/{shot}"
    def srcset(ext):
        return ", ".join(f"{base}-{w}.{ext} {w}w" for w in SHOT_WIDTHS)
    loading = 'fetchpriority="high"' if eager else 'loading="lazy"'
    cls_attr = f' class="{cls}"' if cls else ""
    return (f'<picture{cls_attr}>'
            f'<source type="image/avif" srcset="{srcset("avif")}" sizes="{SHOT_SIZES}">'
            f'<source type="image/webp" srcset="{srcset("webp")}" sizes="{SHOT_SIZES}">'
            f'<img src="{base}-600.jpg" width="1320" height="2868" alt="{attr(alt)}" {loading} decoding="async">'
            f'</picture>')


def store_badge(lang, t, url, where):
    """The App Store call to action: Apple's badge linking to the app once appStoreURL is set,
    'Coming soon to the App Store' (not a link) until then."""
    if url:
        return (f'<p class="store store-{where}"><a class="store-badge" href="{html.escape(url)}">'
                f'<img src="/assets/img/badges/app-store-badge-{lang}.svg" width="150" height="50" '
                f'alt="{attr(t["badge_alt"])}"></a></p>')
    return (f'<p class="store store-{where}"><span class="store-soon">'
            f'<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><circle cx="12" cy="12" r="9" fill="none" '
            f'stroke="currentColor" stroke-width="2"/><path d="M12 7v5l3.5 2" fill="none" stroke="currentColor" '
            f'stroke-width="2" stroke-linecap="round"/></svg>{t["coming_soon"]}</span></p>')


def maker_parts(lang, config):
    m = config.get("maker", {})
    photo = quote = ""
    if m.get("photo"):
        photo = (f'<img class="maker-photo" src="{html.escape(m["photo"])}" width="160" height="160" '
                 f'alt="{attr(m.get("photo_alt_" + lang, ""))}" loading="lazy" decoding="async">')
    if m.get("quote_" + lang):
        who = html.escape(m.get("name", ""))
        role = html.escape(m.get("role_" + lang, ""))
        cite = ", ".join(x for x in (who, role) if x)
        quote = (f'<figure class="maker-quote"><blockquote><p>{html.escape(m["quote_" + lang])}</p></blockquote>'
                 + (f'<figcaption>{cite}</figcaption>' if cite else "") + '</figure>')
    elif m.get("name"):
        role = html.escape(m.get("role_" + lang, ""))
        quote = f'<p class="maker-name">{html.escape(m["name"])}' + (f", {role}" if role else "") + "</p>"
    return photo, quote


def home_context(lang, config):
    t = json.loads(read(SRC, "strings", f"{lang}.json"))
    ctx = {k: v for k, v in t.items() if isinstance(v, str)}
    ctx["lang"] = lang
    prefix = "/es" if lang == "es" else ""
    ctx["privacy_url"] = f"{prefix}/privacy/"
    ctx["support_url"] = f"{prefix}/support/"
    url = config.get("appStoreURL", "").strip()
    ctx["store_badge_hero"] = store_badge(lang, t, url, "hero")
    ctx["store_badge_cta"] = store_badge(lang, t, url, "cta")
    # Keep each part of "7-day free trial · $4.99 once · No subscription" on one line.
    ctx["price_line"] = " · ".join(f'<span class="nowrap">{part}</span>' for part in t["price_line"].split(" · "))
    ctx["shot_hero"] = picture(lang, "01-session", t["shot_alt_01-session"], eager=True)

    prompts = ["Visual", "Verbal", "Física"] if lang == "es" else ["Visual", "Verbal", "Physical"]
    ctx["demo_prompt_buttons"] = "\n            ".join(
        f'<button type="button" class="big big-prompt" data-prompt="{p}">{p}</button>' for p in prompts)
    demo = {
        "goals": [t["demo_goal_ab"], t["demo_goal_cd"]],
        "initials": ["AB", "CD"],
        "recorded": t["demo_live_recorded"],
        "undo": t["demo_live_undo"], "cleared": t["demo_live_cleared"],
        "nothingToUndo": t["demo_live_nothing_to_undo"], "pct": t["demo_live_pct"],
        "seeSummary": t["demo_see_summary"], "hideSummary": t["demo_hide_summary"],
        "student": t["demo_student"],
        "calc": {k[5:]: t[k] for k in t if k.startswith("calc_")},
    }
    # Unescape &amp; for JS (it sets textContent); keep "</" out of the inline JSON.
    ctx["demo_data"] = json.dumps(demo, ensure_ascii=False).replace("&amp;", "&").replace("</", "<\\/")

    steps, phone = [], []
    for i, step in enumerate(t["steps"], 1):
        alt = t["shot_alt_" + step["shot"]]
        steps.append(
            f'<li class="story-step" data-step="{i}">'
            f'<div class="story-text"><span class="story-num" aria-hidden="true">{i}</span>'
            f'<h3>{step["title"]}</h3><p>{step["text"]}</p></div>'
            f'<div class="phone story-shot">{picture(lang, step["shot"], alt)}</div></li>')
        phone.append(picture(lang, step["shot"], "", cls="story-phone-shot" + (" is-active" if i == 1 else "")))
    ctx["story_steps"] = "\n        ".join(steps)
    # Decorative copies for the sticky phone (the steps carry the alt text).
    ctx["story_phone_shots"] = "\n          ".join(phone)
    ctx["video_steps"] = "\n        ".join(f"<li>{s}</li>" for s in t["video_steps"])
    ctx["privacy_items"] = "\n      ".join(
        f'<li><svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M12 3 5 6v5.5c0 4.3 3 8 7 9.5 4-1.5 7-5.2 7-9.5V6z" fill="none" stroke="currentColor" stroke-width="2" stroke-linejoin="round"/><path d="m8.8 12.2 2.3 2.3 4.3-4.6" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>'
        f'<h3>{it["title"]}</h3><p>{it["text"]}</p></li>' for it in t["privacy_items"])
    ctx["who_items"] = "\n      ".join(f'<li><h3>{it["title"]}</h3><p>{it["text"]}</p></li>' for it in t["who_items"])
    ctx["pricing_items"] = "\n        ".join(f"<li>{it}</li>" for it in t["pricing_items"])
    ctx["faq_items"] = "\n      ".join(
        f'<details><summary>{it["q"]}</summary><p>{it["a"]}</p></details>' for it in t["faq_items"])
    ctx["maker_photo"], ctx["maker_quote"] = maker_parts(lang, config)
    w = t["calc_week"].replace("{n}", "50").replace("{minutes}", t["calc_minute_other"])
    y = t["calc_year"].replace("{n}", "30").replace("{hours}", t["calc_hour_other"])
    ctx["calc_week_default"], ctx["calc_year_default"] = w, y
    return t, ctx


